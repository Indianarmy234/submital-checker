
import os
from contextlib import contextmanager
from pathlib import Path

import bcrypt
import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv


BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")


def get_db_config():
    required = ["DB_HOST", "DB_NAME", "DB_USER", "DB_PASSWORD"]

    missing = [key for key in required if not os.getenv(key)]
    if missing:
        raise RuntimeError(
            "Missing database environment variables: " + ", ".join(missing)
        )

    return {
        "host": os.getenv("DB_HOST"),
        "port": int(os.getenv("DB_PORT", "5432")),
        "dbname": os.getenv("DB_NAME"),
        "user": os.getenv("DB_USER"),
        "password": os.getenv("DB_PASSWORD"),
        "sslmode": "require",
        "row_factory": dict_row,
        "connect_timeout": 15,
    }


@contextmanager
def get_connection():
    with psycopg.connect(**get_db_config()) as conn:
        yield conn


def hash_password(password: str) -> str:
    if not password:
        raise ValueError("Password cannot be empty.")

    return bcrypt.hashpw(
        password.encode("utf-8"),
        bcrypt.gensalt()
    ).decode("utf-8")


def verify_password(password: str, stored_hash: str) -> bool:
    if not password or not stored_hash:
        return False

    try:
        return bcrypt.checkpw(
            password.encode("utf-8"),
            stored_hash.encode("utf-8")
        )
    except (ValueError, TypeError):
        return False


def create_tables():
    with get_connection() as conn:

        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                mobile TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL DEFAULT 'Employee',
                company TEXT NOT NULL,
                is_active BOOLEAN NOT NULL DEFAULT TRUE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS sessions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                token TEXT NOT NULL UNIQUE,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at TIMESTAMPTZ NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS submissions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_name TEXT,
                submittal_number TEXT,
                submission_date TEXT,
                supplier_contractor TEXT,
                material_description TEXT,
                manufacturer TEXT,
                specification_reference TEXT,
                revision_number TEXT,
                warranty TEXT,
                approval_status TEXT DEFAULT 'Submitted',
                submitted_by BIGINT NOT NULL REFERENCES users(id),
                company TEXT NOT NULL,
                deleted_at TIMESTAMPTZ,
                deleted_by BIGINT REFERENCES users(id),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS drawing_submissions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                project_name TEXT,
                client TEXT,
                contractor TEXT,
                drawing_title TEXT,
                drawing_number TEXT,
                submittal_ref_no TEXT,
                revision_number TEXT,
                drawn_by TEXT,
                checked_by TEXT,
                sub_date TEXT,
                form_date TEXT,
                detail TEXT,
                description TEXT,
                legends TEXT,
                notes TEXT,
                approval_status TEXT DEFAULT 'Submitted',
                submitted_by BIGINT NOT NULL REFERENCES users(id),
                company TEXT NOT NULL,
                deleted_at TIMESTAMPTZ,
                deleted_by BIGINT REFERENCES users(id),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS consultant_comments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                document_type TEXT NOT NULL,
                submission_id BIGINT NOT NULL,
                drawing_number TEXT,
                comment TEXT NOT NULL,
                status TEXT DEFAULT 'Open',
                created_by BIGINT NOT NULL REFERENCES users(id),
                company TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_material_duplicate
            ON submissions(submittal_number, revision_number, company)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_drawing_duplicate
            ON drawing_submissions(drawing_number, revision_number, company)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_material_owner
            ON submissions(submitted_by, company)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_drawing_owner
            ON drawing_submissions(submitted_by, company)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_session_token
            ON sessions(token)
        """)

        # Activate ONLY the existing configured Super Admin.
        # Do not create a new user or change the existing password.

        admin_mobile = os.getenv("SUPER_ADMIN_MOBILE")

        if admin_mobile:
            conn.execute("""
                UPDATE users
                SET is_active = TRUE
                WHERE mobile = %s
                  AND role = 'Super Admin'
            """, (admin_mobile,))


def get_database_path():
    return "Supabase PostgreSQL"


def get_database_info():
    with get_connection() as conn:
        rows = conn.execute("""
            SELECT table_name AS name
            FROM information_schema.tables
            WHERE table_schema = current_schema()
              AND table_type = 'BASE TABLE'
            ORDER BY table_name
        """).fetchall()

        return {
            "database": "Supabase PostgreSQL",
            "tables": [row["name"] for row in rows]
        }


def get_record_counts():
    tables = [
        "users",
        "sessions",
        "submissions",
        "drawing_submissions",
        "consultant_comments"
    ]

    with get_connection() as conn:
        result = {}

        for table in tables:
            row = conn.execute(
                f"SELECT COUNT(*) AS total FROM {table}"
            ).fetchone()
            result[table] = row["total"]

        return result
